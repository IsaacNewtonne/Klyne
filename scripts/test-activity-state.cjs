const assert=require('assert'),fs=require('fs'),vm=require('vm');
let now=1000,timers=new Map(),timerId=0;
const window={dispatchEvent(){}};
vm.runInNewContext(fs.readFileSync('apps/studio/web/activity.js','utf8'),{window,performance:{now:()=>now},CustomEvent:class{},setTimeout:fn=>{timers.set(++timerId,fn);return timerId},clearTimeout:id=>timers.delete(id)});
const a=window.klyneActivity,events=[];
const fixture={status:'Working',activity:null,evidence:[],activity_events:events};
const snap=()=>a.snapshot({selected:'a',snapshot:fixture});
snap();
const event=(type,data)=>{events.push({seq:events.length+1,type,data});snap();};
event('tool:start',{id:'a',tool:'files',operation:'Reading first file'});
event('tool:start',{id:'b',tool:'files',operation:'Writing second file'});
event('tool:start',{id:'c',tool:'browser',operation:'Opening page'});
assert.equal(a.state().operations.length,3);
event('tool:waiting',{id:'c',operation:'Awaiting page'});
assert.equal(a.state().mode,'working');
event('tool:result',{id:'a'});
assert.equal(a.state().operations.find(o=>o.id==='a').direction,'inbound');
event('tool:complete',{id:'a'});
assert.deepEqual(Array.from(a.state().operations,o=>o.id),['b','c']);
event('tool:complete',{id:'b'});
assert.equal(a.state().mode,'waiting');
event('tool:error',{id:'c'});
assert.equal(a.state().failures[0].tool,'browser');
now+=900;for(const fn of [...timers.values()])fn();
assert.equal(a.state().flashes.length,0,'Feedback expires without a visible renderer');
a.emit('klyne:thinking');assert.equal(a.state().mode,'working');
a.emit('klyne:reviewing');assert.equal(a.state().mode,'working');
a.emit('system:cpu_updated',{cpu_percent:12.5});assert.equal(a.state().cpuPercent,12.5);
a.emit('system:cpu_updated',{cpu_percent:null});assert.equal(a.state().cpuPercent,null);
event('tool:start',{id:'d',tool:'terminal'});
a.emit('system:connection_changed',{connected:false});assert.equal(a.state().operations.length,0);
snap();assert.equal(a.state().mode,'disconnected');
a.emit('system:connection_changed',{connected:true});snap();
assert.equal(a.state().operations.length,1);assert.equal(a.state().flashes.length,0);
fixture.status='Needs input';fixture.pending={proposal:{}};snap();
assert.equal(a.state().mode,'input');assert.equal(a.state().operations.length,0);
fixture.status='Completed';fixture.pending=null;snap();assert.equal(a.state().mode,'complete');
a.snapshot({selected:'b',snapshot:{...fixture,activity_events:events}});
assert.equal(a.state().flashes.length,0,'Selecting history never replays completion flashes');
console.log('Activity reducer: same-tool concurrency, direction, waits, expiry, aliases, real CPU, disconnect/reconnect, input, replay passed');
